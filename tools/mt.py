import json, sys
J = sys.argv[1]; T = json.load(open(f"{J}/audio/timing.json")); P = json.load(open(f"{J}/plan.json"))
words = [{k: q[k] for k in ("w", "s", "e", "sp", "line")} for q in T["words"]]
open(f"{J}/src/times.js", "w").write(f"""// generated by tools/mt.py
export const DURATION = {T['dur']};
export const WORDS = {json.dumps(words)};
export const LINES = {json.dumps(T['lines'])};
export const SPEAKER_COLORS = {json.dumps(P['colors'])};
export const TITLE = {json.dumps(P['title'])};
export const LOCS = {json.dumps(P['locs'])};
export const INNER_CUTS = {json.dumps(P.get('inner_cuts', []))};
export const TIME_SKIPS = {json.dumps(P.get('time_skips', []))};
export const w = (line, re) => {{ const x = WORDS.find((q) => q.line === line && new RegExp(re, 'i').test(q.w)); if (!x) throw new Error('no word ' + line + ' ' + re); return x.s; }};
export const we = (line, re) => {{ const x = WORDS.find((q) => q.line === line && new RegExp(re, 'i').test(q.w)); if (!x) throw new Error('no word ' + line + ' ' + re); return x.e; }};
export const talking = (t, sp) => WORDS.some((q) => q.sp === sp && t > q.s && t < q.e - 0.02);
""")
print("times.js ok")
